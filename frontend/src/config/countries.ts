// - La opción "Sin especificar" (que representa `null`) NO vive aquí;
//   se añade en la UI de `PersonalDataSection`. `countries.ts` modela
//   solo países y territorios reales.
// - Nombres comunes (p. ej. "Estados Unidos", no "Estados Unidos de
//   América"), con acentos correctos en cada idioma.

