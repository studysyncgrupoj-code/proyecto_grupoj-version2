/**
 * Devuelve el catálogo ordenado por nombre en el locale indicado.
 * El orden por defecto (sin locale) es por `nameEs`.
 *
 * `localeCompare` con locale explícito respeta acentos y reglas de
 * ordenación de cada idioma (p. ej. "Ñ" en español, "Å" en sueco).
 */
export function getCountriesSorted(locale: 'es' | 'en' = 'es'): Country[] {
  return [...COUNTRIES].sort((a, b) =>
    locale === 'en'
      ? a.nameEn.localeCompare(b.nameEn, 'en')
      : a.nameEs.localeCompare(b.nameEs, 'es'),
  );
}
